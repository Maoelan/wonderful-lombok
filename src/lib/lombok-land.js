export const lombokLandBounds = {
  "west": 115.8212,
  "south": -8.9561,
  "east": 116.72511,
  "north": -8.21031
};

export function isPointInLombokLand(lat, lng) {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  if (lng < lombokLandBounds.west || lng > lombokLandBounds.east || lat < lombokLandBounds.south || lat > lombokLandBounds.north) return false;
  let inside = false;
  for (let i = 0, j = lombokLandRing.length - 1; i < lombokLandRing.length; j = i++) {
    const [xi, yi] = lombokLandRing[i];
    const [xj, yj] = lombokLandRing[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
