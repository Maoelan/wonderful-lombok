export const demoImage = key => `/images/lombok-ai/${key}-1280.webp`;
export const demoImageKeys = ['hero-coast', 'sasak-culture', 'gili-snorkeling', 'couples-sunset', 'kuta-mandalika', 'tanjung-aan', 'three-gilis', 'sembalun-rinjani', 'senggigi-coast', 'local-journey'];
export function isDemoImage(value) {
  const match = typeof value === 'string' && /^\/images\/lombok-ai\/([a-z-]+)-(480|720|960|1280|1600)\.webp$/.exec(value);
  return Boolean(match && demoImageKeys.includes(match[1]));
}

function refreshItem(item, previous, next) {
  if (!previous || !next) return item;
  const result = { ...item };
  if (item.image === previous.image) result.image = demoImage(next.image);
  if (Array.isArray(item.images) && item.images.length &&
      item.images.every(image => [previous.image, ...previous.images].includes(image))) {
    result.images = next.images.map(demoImage);
  }
  return result;
}
export function refreshDemoImages(catalog) {
  const settings = { ...catalog.settings };
  for (const field of ['heroImage', 'aboutImage']) {
    if (settings[field] === legacy.settings[field]) settings[field] = demoImage(demo.settings[field]);
  }
  return {
    ...catalog, settings,
    packages: catalog.packages.map(item => refreshItem(item, legacy.packages[item.slug], demo.packages[item.slug])),
    destinations: catalog.destinations.map(item => refreshItem(item, legacy.destinations[item.name], demo.destinations[item.name]))
  };
}

